/**
 * Bundles server/send-report.ts into api/send-report.js for Vercel.
 *
 * Vercel compiles api/*.ts on its own using the root tsconfig (ES modules), which breaks
 * functions that share code with src/. Bundling to a single CommonJS file avoids that, so
 * the endpoint can reuse the questionnaire's scoring logic. The output is committed.
 */
import { build } from 'esbuild'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

await build({
  entryPoints: [resolve(root, 'server/send-report.ts')],
  outfile: resolve(root, 'api/send-report.js'),
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'cjs',
  external: ['@upstash/redis'],
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/send-report.ts. Do not edit by hand.' },
})
console.log('[api] built api/send-report.js')
